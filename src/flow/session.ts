import type { Page } from "playwright-core";
import { tapRpcs, type RpcTap } from "../browser/rpc.js";
import { getFlowPage } from "../browser/connect.js";
import { extractMedia, parseBatchExecute, type FlowMedia } from "./batchexecute.js";
import { pendingApproval, readTranscript, type Approval, type ChatMessage } from "./chat.js";
import { attachInputs, type AttachedInputs } from "./assets.js";
import { clearPrompt, download, openProject, sendPrompt, waitForAgentTurn, type DownloadedMedia, type ProjectChoice } from "./ui.js";
import { assertApprovalRequired } from "./settings.js";
import { checkUploadable } from "./upload.js";

/*
 * Turn-by-turn access to the Flow agent: every call returns as soon as the agent has
 * finished speaking, with its exact words, so the caller can decide the next step itself.
 * Credits are only ever spent through decide(), and only within the caller's budget.
 */

// Flow stamps media with server time; allow for clock skew against this machine.
const CLOCK_SKEW_S = 15;
const POLL_MS = 20_000;

export interface MediaInfo {
  id: string;
  kind?: "image" | "video";
  model?: string;
  prompt?: string;
  /** True once the full-size file can be downloaded. */
  ready: boolean;
}

export interface TurnResult {
  projectId: string;
  projectUrl: string;
  /** Messages added during this call: what was sent and everything the agent replied. */
  messages: ChatMessage[];
  /** The agent's reply text in one piece, for quick reading. */
  reply: string;
  /** Set when the agent is waiting for Approve / Reject before spending credits. */
  pendingApproval?: Approval;
  /** Media the agent created during this call. Fetch files with waitForMedia. */
  media: MediaInfo[];
  /** Epoch seconds marking the start of this call, for waitForMedia's `since`. */
  since: number;
}

export type ProgressFn = (message: string, percent?: number) => void;

const isFullSize = (m: FlowMedia) => /^https:\/\/flow-content\.google\/(video|image)\//.test(m.url) && (m.kind !== "video" || m.url.includes("/video/"));

/** Collects every media record the page receives, keyed by id. */
class MediaWatch {
  readonly found = new Map<string, FlowMedia>();
  private tap?: RpcTap;

  static async start(page: Page): Promise<MediaWatch> {
    const watch = new MediaWatch();
    watch.tap = await tapRpcs(page, (_, body) => {
      for (const { data } of parseBatchExecute(body)) extractMedia(data, watch.found);
    });
    return watch;
  }

  async stop(): Promise<void> {
    await this.tap?.stop();
  }

  /** Media generated by a model since `since`, excluding anything known beforehand. */
  generated(since: number, exclude: Set<string>): FlowMedia[] {
    return [...this.found.values()].filter((m) => !!m.model && !exclude.has(m.id) && (m.createdAt ?? 0) >= since);
  }
}

const summary = (m: FlowMedia): MediaInfo => ({
  id: m.id,
  kind: m.kind,
  ...(m.model ? { model: m.model } : {}),
  ...(m.prompt ? { prompt: m.prompt } : {}),
  ready: isFullSize(m),
});

const replyText = (messages: ChatMessage[]) =>
  messages
    .filter((m) => m.role === "agent")
    .map((m) => m.text)
    .join("\n\n");

async function finishTurn(
  page: Page,
  projectId: string,
  before: number,
  watch: MediaWatch,
  since: number,
  exclude: Set<string>,
  includeThinking: boolean,
): Promise<TurnResult> {
  await waitForAgentTurn(page);
  // Images and video placeholders are announced just after the agent's last words.
  await page.waitForTimeout(1_500);
  const all = await readTranscript(page, { includeThinking });
  const messages = all.slice(before);
  const approval = pendingApproval(messages);
  return {
    projectId,
    projectUrl: page.url(),
    messages,
    reply: replyText(messages),
    ...(approval ? { pendingApproval: approval } : {}),
    media: watch.generated(since, exclude).map(summary),
    since,
  };
}

export interface ChatOptions extends ProjectChoice {
  message: string;
  /** Local files (images or videos the user holds rights to); uploaded once per project, then reused. */
  attachments?: string[];
  /** The user confirmed they hold the rights to the attachments (Flow asks on upload). */
  confirmRights?: boolean;
  /** Media already in the project to attach, from listAssets. */
  mediaIds?: string[];
  includeThinking?: boolean;
}

export type ChatResult = TurnResult & { inputs?: AttachedInputs };

/** Sends one message to the Flow agent and returns once it has finished replying. */
export async function chatTurn(options: ChatOptions): Promise<ChatResult> {
  options.attachments?.forEach(checkUploadable);
  const page = await getFlowPage();
  await page.bringToFront();
  const projectId = await openProject(page, options);
  // A message can lead the agent to spend credits; that must go through its approval request.
  await assertApprovalRequired(page, projectId);
  const watch = await MediaWatch.start(page);
  try {
    await clearPrompt(page);
    const attached = await attachInputs(page, projectId, { files: options.attachments, mediaIds: options.mediaIds, confirmRights: options.confirmRights });
    const before = (await readTranscript(page)).length;
    const exclude = new Set([...watch.found.keys(), ...attached.mediaIds]);
    const since = Date.now() / 1000 - CLOCK_SKEW_S;
    await sendPrompt(page, options.message);
    const turn = await finishTurn(page, projectId, before, watch, since, exclude, !!options.includeThinking);
    return { ...turn, ...(attached.mediaIds.length ? { inputs: attached } : {}) };
  } finally {
    await watch.stop();
  }
}

export interface DecideOptions {
  projectId: string;
  decision: "approve" | "reject";
  /** Highest quoted cost to approve; a higher quote is rejected instead. */
  maxCredits: number;
  includeThinking?: boolean;
}

export type DecideResult = TurnResult & { decision: "approved" | "rejected" | "rejected_over_budget"; credits?: number };

/**
 * Answers the agent's pending spend approval. Never picks "Always approve", never approves a
 * quote it cannot read, and turns an over-budget approval into a rejection.
 */
export async function decide(options: DecideOptions): Promise<DecideResult> {
  const page = await getFlowPage();
  await page.bringToFront();
  const projectId = await openProject(page, { projectId: options.projectId });
  const transcript = await readTranscript(page);
  const approval = pendingApproval(transcript);
  if (!approval) throw new Error("The Flow agent is not waiting for an approval in this project.");

  let decision: DecideResult["decision"] = options.decision === "approve" ? "approved" : "rejected";
  if (decision === "approved") {
    if (approval.credits === undefined) throw new Error(`Could not read the cost in "${approval.question}"; not approving.`);
    if (approval.credits > options.maxCredits) decision = "rejected_over_budget";
  }

  const watch = await MediaWatch.start(page);
  try {
    const exclude = new Set(watch.found.keys());
    const since = Date.now() / 1000 - CLOCK_SKEW_S;
    const card = page.locator("flow-permission-message").last();
    const choice = decision === "approved" ? "Approve" : "Reject";
    await card.getByRole("radio", { name: choice, exact: true }).click();
    const turn = await finishTurn(page, projectId, transcript.length, watch, since, exclude, !!options.includeThinking);
    return { ...turn, decision, ...(approval.credits !== undefined ? { credits: approval.credits } : {}) };
  } finally {
    await watch.stop();
  }
}

export interface WaitOptions {
  projectId: string;
  /** Media to wait for. Without it, every model-made media item since `since` counts. */
  mediaIds?: string[];
  since?: number;
  timeoutMs?: number;
  onProgress?: ProgressFn;
}

export interface WaitResult {
  projectId: string;
  /** completed: every requested item is downloaded. pending: call again later (nothing is lost). */
  status: "completed" | "pending";
  files: DownloadedMedia[];
  /** Media still rendering when the wait ended. */
  pending: MediaInfo[];
  /** Anything the agent said while waiting. */
  messages: ChatMessage[];
}

/** Reads a render percentage Flow shows on a placeholder tile, if any. */
async function renderPercent(page: Page): Promise<number | undefined> {
  const texts = await page.getByText(/^\d{1,3}%$/).allInnerTexts().catch(() => []);
  const values = texts.map((t) => Number.parseInt(t, 10)).filter((n) => n >= 0 && n <= 100);
  return values.length ? Math.min(...values) : undefined;
}

/**
 * Waits until the requested media are finished and downloads them. Flow only reveals a
 * finished video's file when the page fetches its details, so the project is reloaded
 * every 20 s (free).
 */
export async function waitForMedia(options: WaitOptions): Promise<WaitResult> {
  const page = await getFlowPage();
  await page.bringToFront();
  const projectId = await openProject(page, { projectId: options.projectId });
  const before = (await readTranscript(page)).length;
  const watch = await MediaWatch.start(page);
  const wanted = options.mediaIds ? new Set(options.mediaIds) : undefined;
  const since = options.since ?? 0;
  const matches = (m: FlowMedia) => (wanted ? wanted.has(m.id) : !!m.model && (m.createdAt ?? 0) >= since);
  const tracked = () => [...watch.found.values()].filter(matches);
  // Short by default so one call stays within MCP clients' tool time limits; callers poll again.
  const deadline = Date.now() + (options.timeoutMs ?? 90_000);
  try {
    await page.reload({ waitUntil: "domcontentloaded" });
    await page.waitForTimeout(5_000);
    while (true) {
      const items = tracked();
      const expected = wanted ? wanted.size : 1;
      if (items.length >= expected && items.every(isFullSize)) break;
      if (Date.now() >= deadline) break;
      const percent = await renderPercent(page);
      options.onProgress?.(
        items.length ? `${items.filter(isFullSize).length}/${items.length} ready${percent !== undefined ? `, rendering ${percent}%` : ""}` : "waiting for Flow to list the media",
        percent,
      );
      // A refresh cycle takes POLL_MS plus ~5 s; skip one that would end past the deadline.
      if (deadline - Date.now() < POLL_MS + 5_000) break;
      await page.waitForTimeout(POLL_MS);
      await page.reload({ waitUntil: "domcontentloaded" });
      await page.waitForTimeout(5_000);
    }
    const items = tracked();
    const ready = items.filter(isFullSize);
    const files = await download(page, ready);
    options.onProgress?.(`${files.length} file(s) downloaded`, 100);
    const messages = (await readTranscript(page)).slice(before);
    const pending = items.filter((m) => !isFullSize(m)).map(summary);
    const done = pending.length === 0 && items.length >= (wanted ? wanted.size : 1);
    return { projectId, status: done ? "completed" : "pending", files, pending, messages };
  } finally {
    await watch.stop();
  }
}

export async function transcript(projectId: string, includeThinking = false): Promise<{ projectId: string; messages: ChatMessage[]; pendingApproval?: Approval }> {
  const page = await getFlowPage();
  await openProject(page, { projectId });
  await page.locator(".messages-list").first().waitFor({ timeout: 15_000 }).catch(() => {});
  const messages = await readTranscript(page, { includeThinking });
  const approval = pendingApproval(messages);
  return { projectId, messages, ...(approval ? { pendingApproval: approval } : {}) };
}
